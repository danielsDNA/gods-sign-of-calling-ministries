grant select on public.site_settings, public.hero_phrases, public.service_times,
  public.sermons, public.events, public.ministries, public.leadership_team,
  public.gallery_images to anon, authenticated;

create policy "Public can read site settings" on public.site_settings
  for select to anon, authenticated using (true);
create policy "Public can read active hero phrases" on public.hero_phrases
  for select to anon, authenticated using (active);
create policy "Public can read active service times" on public.service_times
  for select to anon, authenticated using (active);
create policy "Public can read published sermons" on public.sermons
  for select to anon, authenticated using (published);
create policy "Public can read published events" on public.events
  for select to anon, authenticated using (published);
create policy "Public can read active ministries" on public.ministries
  for select to anon, authenticated using (active);
create policy "Public can read active leaders" on public.leadership_team
  for select to anon, authenticated using (active);
create policy "Public can read active gallery images" on public.gallery_images
  for select to anon, authenticated using (active);

