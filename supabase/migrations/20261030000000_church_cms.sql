-- Grace Church CMS schema for Supabase PostgreSQL.
-- The current app runtime continues to use its existing MySQL database.
-- Passwords are bcrypt hashes produced by the application; never insert plaintext passwords.

create table public.admin_users (
  id bigint generated by default as identity primary key,
  email varchar(255) not null,
  password_hash varchar(255) not null,
  display_name varchar(100),
  role varchar(50) not null default 'editor' check (role in ('owner', 'editor')),
  reset_token varchar(128),
  reset_token_expiry timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index admin_users_email_lower_unique on public.admin_users (lower(email));

create table public.site_settings (
  id bigint generated by default as identity primary key,
  key varchar(100) not null unique,
  value text,
  updated_at timestamptz not null default now()
);

create table public.hero_phrases (
  id bigint generated by default as identity primary key,
  phrase varchar(255) not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.service_times (
  id bigint generated by default as identity primary key,
  day varchar(50) not null,
  time varchar(50) not null,
  label varchar(100) not null,
  location varchar(150),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.sermons (
  id bigint generated by default as identity primary key,
  title varchar(255) not null,
  speaker varchar(150),
  series varchar(150),
  scripture varchar(150),
  description text,
  preached_on date,
  media_type varchar(20) not null default 'youtube',
  media_url text not null,
  thumbnail_url text,
  featured boolean not null default false,
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index sermons_public_sort on public.sermons (published, preached_on desc, sort_order);

create table public.events (
  id bigint generated by default as identity primary key,
  title varchar(255) not null,
  category varchar(100) not null default 'Event',
  description text,
  starts_at timestamptz not null,
  ends_at timestamptz,
  location varchar(255),
  image_url text,
  featured boolean not null default false,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index events_public_start on public.events (published, starts_at);

create table public.prayer_requests (
  id bigint generated by default as identity primary key,
  name varchar(150),
  email varchar(255),
  phone varchar(50),
  request text not null,
  is_private boolean not null default true,
  status varchar(50) not null default 'new',
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.ministries (
  id bigint generated by default as identity primary key,
  name varchar(150) not null,
  tagline varchar(255),
  description text,
  image_url text,
  meeting_time varchar(150),
  contact_name varchar(150),
  contact_email varchar(255),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ministries_public_sort on public.ministries (active, sort_order);

create table public.leadership_team (
  id bigint generated by default as identity primary key,
  name varchar(150) not null,
  title varchar(150),
  bio text,
  image_url text,
  email varchar(255),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index leadership_public_sort on public.leadership_team (active, sort_order);

create table public.gallery_images (
  id bigint generated by default as identity primary key,
  image_url text not null,
  caption varchar(255),
  category varchar(100) not null default 'General',
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index gallery_images_public_sort on public.gallery_images (active, sort_order);

create function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger admin_users_set_updated_at before update on public.admin_users
for each row execute function public.set_updated_at();
create trigger site_settings_set_updated_at before update on public.site_settings
for each row execute function public.set_updated_at();
create trigger sermons_set_updated_at before update on public.sermons
for each row execute function public.set_updated_at();
create trigger events_set_updated_at before update on public.events
for each row execute function public.set_updated_at();
create trigger prayer_requests_set_updated_at before update on public.prayer_requests
for each row execute function public.set_updated_at();
create trigger ministries_set_updated_at before update on public.ministries
for each row execute function public.set_updated_at();
create trigger leadership_team_set_updated_at before update on public.leadership_team
for each row execute function public.set_updated_at();

